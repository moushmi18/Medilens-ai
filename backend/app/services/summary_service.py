"""Doctor summary PDF generation service.

Generates a PDF summary for healthcare provider review.
IMPORTANT: Contains factual results and patient questions only.
NEVER includes diagnosis, treatment recommendations, or dosages.
"""
import io
from datetime import datetime
from typing import Any
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.exceptions import NotFoundError
from app.core.logging import get_logger
from app.database.models import MedicalReport, ExtractedResult, User, Conversation, Message

logger = get_logger(__name__)


class SummaryService:
    """Service for generating doctor summary PDFs."""
    
    def __init__(self, db: Session):
        self.db = db
    
    def generate_summary(
        self,
        user: User,
        report_id: UUID,
        include_questions: bool = True,
    ) -> tuple[bytes, str]:
        """Generate a PDF summary for a report.
        
        Args:
            user: Current user
            report_id: Report to summarize
            include_questions: Whether to include patient's questions
            
        Returns:
            Tuple of (PDF bytes, filename)
        """
        report = self.db.execute(
            select(MedicalReport).where(
                MedicalReport.id == report_id,
                MedicalReport.user_id == user.id,
            )
        ).scalar_one_or_none()
        
        if not report:
            raise NotFoundError("Report", str(report_id))
        
        results = self.db.execute(
            select(ExtractedResult).where(
                ExtractedResult.report_id == report_id
            ).order_by(ExtractedResult.test_name)
        ).scalars().all()
        
        questions = []
        if include_questions:
            conversations = self.db.execute(
                select(Conversation).where(
                    Conversation.report_id == report_id,
                    Conversation.user_id == user.id,
                )
            ).scalars().all()
            
            for conv in conversations:
                messages = self.db.execute(
                    select(Message).where(
                        Message.conversation_id == conv.id,
                        Message.role == "user",
                    )
                ).scalars().all()
                questions.extend([m.content for m in messages])
        
        pdf_content = self._generate_pdf_content(
            report=report,
            results=list(results),
            questions=questions,
        )
        
        filename = f"medilens_summary_{report_id}_{datetime.utcnow().strftime('%Y%m%d')}.pdf"
        
        logger.info(
            "summary_generated",
            user_id=str(user.id),
            report_id=str(report_id),
            result_count=len(results),
            question_count=len(questions),
        )
        
        return pdf_content, filename
    
    def _generate_pdf_content(
        self,
        report: MedicalReport,
        results: list[ExtractedResult],
        questions: list[str],
    ) -> bytes:
        """Generate PDF content.
        
        Note: This is a simple text-based PDF generator.
        For production, consider using ReportLab or WeasyPrint.
        """
        try:
            from reportlab.lib.pagesizes import letter
            from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
            from reportlab.lib.units import inch
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
            from reportlab.lib import colors
        except ImportError:
            return self._generate_text_fallback(report, results, questions)
        
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter)
        styles = getSampleStyleSheet()
        story = []
        
        title_style = ParagraphStyle(
            'Title',
            parent=styles['Heading1'],
            fontSize=18,
            spaceAfter=12,
        )
        
        story.append(Paragraph("MediLens AI - Report Summary", title_style))
        story.append(Paragraph(f"<b>Report:</b> {report.original_filename}", styles['Normal']))
        story.append(Paragraph(f"<b>Generated:</b> {datetime.utcnow().strftime('%Y-%m-%d %H:%M')}", styles['Normal']))
        story.append(Spacer(1, 0.25*inch))
        
        story.append(Paragraph(
            "<i>This summary is generated by MediLens AI for educational purposes. "
            "It contains extracted lab values and patient questions. "
            "No diagnosis or treatment recommendations are provided.</i>",
            styles['Normal']
        ))
        story.append(Spacer(1, 0.25*inch))
        
        if results:
            story.append(Paragraph("Extracted Lab Results", styles['Heading2']))
            
            table_data = [['Test Name', 'Value', 'Unit', 'Reference Range', 'Status']]
            for result in results:
                ref_range = (
                    f"{result.reference_range_low}-{result.reference_range_high}"
                    if result.reference_range_low and result.reference_range_high
                    else "N/A"
                )
                status = ""
                if result.is_abnormal is True:
                    status = "Outside Range"
                elif result.is_abnormal is False:
                    status = "Normal"
                else:
                    status = "Unknown"
                
                table_data.append([
                    result.test_name,
                    result.observed_value or "N/A",
                    result.unit or "",
                    ref_range,
                    status,
                ])
            
            table = Table(table_data)
            table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.grey),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
                ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
                ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('FONTSIZE', (0, 0), (-1, 0), 10),
                ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
                ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
                ('GRID', (0, 0), (-1, -1), 1, colors.black),
            ]))
            story.append(table)
            story.append(Spacer(1, 0.25*inch))
        
        if questions:
            story.append(Paragraph("Patient Questions", styles['Heading2']))
            story.append(Paragraph(
                "The following questions were asked by the patient regarding this report:",
                styles['Normal']
            ))
            story.append(Spacer(1, 0.1*inch))
            
            for i, q in enumerate(questions[:10], 1):
                story.append(Paragraph(f"{i}. {q}", styles['Normal']))
            
            if len(questions) > 10:
                story.append(Paragraph(
                    f"... and {len(questions) - 10} more questions",
                    styles['Normal']
                ))
        
        story.append(Spacer(1, 0.5*inch))
        story.append(Paragraph(
            "---",
            styles['Normal']
        ))
        story.append(Paragraph(
            "<i>Generated by MediLens AI - For educational purposes only. "
            "This document does not contain medical advice.</i>",
            styles['Normal']
        ))
        
        doc.build(story)
        buffer.seek(0)
        return buffer.read()
    
    def _generate_text_fallback(
        self,
        report: MedicalReport,
        results: list[ExtractedResult],
        questions: list[str],
    ) -> bytes:
        """Generate a plain text fallback if ReportLab is not available."""
        lines = [
            "=" * 60,
            "MEDILENS AI - REPORT SUMMARY",
            "=" * 60,
            "",
            f"Report: {report.original_filename}",
            f"Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M')}",
            "",
            "DISCLAIMER: This summary is for educational purposes only.",
            "No diagnosis or treatment recommendations are provided.",
            "",
            "-" * 60,
            "EXTRACTED LAB RESULTS",
            "-" * 60,
            "",
        ]
        
        for result in results:
            ref_range = (
                f"{result.reference_range_low}-{result.reference_range_high}"
                if result.reference_range_low and result.reference_range_high
                else "N/A"
            )
            lines.append(f"{result.test_name}: {result.observed_value or 'N/A'} {result.unit or ''}")
            lines.append(f"  Reference Range: {ref_range}")
            lines.append("")
        
        if questions:
            lines.extend([
                "-" * 60,
                "PATIENT QUESTIONS",
                "-" * 60,
                "",
            ])
            for i, q in enumerate(questions[:10], 1):
                lines.append(f"{i}. {q}")
            if len(questions) > 10:
                lines.append(f"... and {len(questions) - 10} more questions")
        
        lines.extend([
            "",
            "=" * 60,
            "Generated by MediLens AI - For educational purposes only.",
            "=" * 60,
        ])
        
        return "\n".join(lines).encode('utf-8')
